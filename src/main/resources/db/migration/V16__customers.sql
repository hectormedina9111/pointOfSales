-- V16: clientes (paso 10 del MVP 3A).
--
-- Ver docs/plan.md, "Clientes" y "Clientes en el 3A". Desviaciones:
--   * document_number no es UNIQUE. Dos tiendas sin conexión pueden registrar a la misma persona y la central debe
--     aceptar los dos registros; el índice solo sirve para buscar. La tienda rechaza duplicados activos
--     (DUPLICATE_CUSTOMER_DOCUMENT). external_code sí es único cuando tiene valor.
--   * display_name es una columna generada. La réplica (ReplicaWriter) no escribe columnas generadas.
--   * El consumidor final (id 1) se siembra ANTES de crear el disparador de réplica: así no entra en el registro
--     de cambios. Cada nodo lo tiene desde esta migración, y la foto inicial de la réplica también lo trae.
--   * customer no tiene customer_id en ninguna tabla todavía: las ventas se enlazan en el siguiente paso.

CREATE TABLE customer (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Código del cliente en el ERP. Opcional y único cuando tiene valor.
    external_code       VARCHAR(50),
    -- PERSON (persona natural) o COMPANY (empresa).
    customer_type       VARCHAR(10)   NOT NULL DEFAULT 'PERSON',
    -- RTN, DNI, PASSPORT o NONE (consumidor final, sin documento).
    document_type       VARCHAR(10)   NOT NULL,
    document_number     VARCHAR(20),
    first_name          VARCHAR(60),
    middle_name         VARCHAR(60),
    last_name           VARCHAR(60),
    second_last_name    VARCHAR(60),
    -- Razón social cuando el cliente es una empresa.
    business_name       VARCHAR(200),
    -- Nombres y apellidos unidos, o la razón social. Se usa en la búsqueda y en los comprobantes.
    display_name        VARCHAR(250) GENERATED ALWAYS AS (
        CAST(CASE WHEN customer_type = 'COMPANY' THEN business_name
                  ELSE btrim(COALESCE(first_name, '') || COALESCE(' ' || middle_name, '')
                             || COALESCE(' ' || last_name, '') || COALESCE(' ' || second_last_name, ''))
             END AS VARCHAR(250))
    ) STORED,
    phone               VARCHAR(20),
    email               VARCHAR(150),
    address             VARCHAR(300),
    -- Lista especial del cliente (mayorista, VIP). NULL: se usa la lista de la sucursal.
    price_list_id       BIGINT        REFERENCES price_list (id),
    active              BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ   NOT NULL,
    created_by          VARCHAR(50)   NOT NULL,
    updated_at          TIMESTAMPTZ   NOT NULL,
    updated_by          VARCHAR(50)   NOT NULL,
    version             INT           NOT NULL DEFAULT 0,
    CONSTRAINT customer_type_ck CHECK (customer_type IN ('PERSON', 'COMPANY')),
    CONSTRAINT customer_document_type_ck CHECK (document_type IN ('RTN', 'DNI', 'PASSPORT', 'NONE')),
    CONSTRAINT customer_person_names_ck CHECK (customer_type <> 'PERSON'
        OR (btrim(COALESCE(first_name, '')) <> '' AND btrim(COALESCE(last_name, '')) <> '')),
    CONSTRAINT customer_company_name_ck CHECK (customer_type <> 'COMPANY'
        OR btrim(COALESCE(business_name, '')) <> ''),
    CONSTRAINT customer_document_number_ck CHECK (document_type = 'NONE'
        OR btrim(COALESCE(document_number, '')) <> ''),
    CONSTRAINT customer_external_code_ck CHECK (external_code IS NULL OR btrim(external_code) <> '')
);

-- Código del ERP único, solo cuando tiene valor.
CREATE UNIQUE INDEX customer_external_code_uk ON customer (external_code) WHERE external_code IS NOT NULL;
-- Búsqueda por documento. No es único (ver la cabecera).
CREATE INDEX customer_document_idx ON customer (document_type, document_number);
-- Búsqueda por nombre sin distinguir mayúsculas.
CREATE INDEX customer_display_name_idx ON customer (lower(display_name));

-- Consumidor final: id fijo 1. La secuencia sigue en 2, así que la central asigna desde 2 en adelante.
INSERT INTO customer (id, customer_type, document_type, first_name, last_name, active,
                      created_at, created_by, updated_at, updated_by, version)
OVERRIDING SYSTEM VALUE
VALUES (1, 'PERSON', 'NONE', 'Consumidor', 'Final', TRUE, now(), 'system', now(), 'system', 0);
SELECT setval(pg_get_serial_sequence('customer', 'id'), 1);

-- Réplica: mismo disparador que las demás tablas principales (ver V9 y V12).
