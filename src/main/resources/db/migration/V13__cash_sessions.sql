-- V13: sesiones de caja y movimientos de efectivo (paso 2 del MVP 3A).
--
-- Ver docs/plan.md, "Caja" y "Decisiones de implementación: 3A paso 2". Desviaciones:
--   * cash_movement.authorized_by se agrega: quién autorizó un retiro (el propio cajero si tiene el privilegio).
--   * Las dos tablas son documentos de la tienda: no se replican (no tienen triggers sync_log_change) y se
--     suben a la central por la cola de salida en el paso 4.
--   * Los usuarios, las cajas y los métodos de pago llegan a la tienda por réplica; las llaves foráneas apuntan a ellos.

CREATE TABLE cash_session (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cash_register_id    BIGINT         NOT NULL REFERENCES cash_register (id),
    -- Cajero que abrió la sesión.
    user_id             BIGINT         NOT NULL REFERENCES app_user (id),
    -- OPEN mientras está abierta; CLOSED después del arqueo.
    status              VARCHAR(10)    NOT NULL,
    opened_at           TIMESTAMPTZ    NOT NULL,
    -- Fondo inicial en efectivo.
    opening_amount      NUMERIC(14,2)  NOT NULL,
    closed_at           TIMESTAMPTZ,
    -- Totales del arqueo, calculados al cerrar.
    expected_total      NUMERIC(14,2),
    counted_total       NUMERIC(14,2),
    -- Contado menos esperado.
    difference          NUMERIC(14,2),
    -- Esperado y contado por método de pago: lista de {method, expected, counted, difference}.
    count_detail        JSONB,
    notes               VARCHAR(500),
    created_at          TIMESTAMPTZ    NOT NULL,
    created_by          VARCHAR(50)    NOT NULL,
    updated_at          TIMESTAMPTZ    NOT NULL,
    updated_by          VARCHAR(50)    NOT NULL,
    version             INT            NOT NULL DEFAULT 0,
    CONSTRAINT cash_session_status_ck CHECK (status IN ('OPEN', 'CLOSED')),
    CONSTRAINT cash_session_opening_amount_ck CHECK (opening_amount >= 0)
);

-- Una sola sesión abierta por caja y una sola por cajero. Son índices parciales: las sesiones cerradas no cuentan.
CREATE UNIQUE INDEX cash_session_open_register_uk ON cash_session (cash_register_id) WHERE status = 'OPEN';
CREATE UNIQUE INDEX cash_session_open_user_uk ON cash_session (user_id) WHERE status = 'OPEN';
-- Listados por caja y por cajero, del más reciente al más antiguo.
CREATE INDEX cash_session_register_opened_idx ON cash_session (cash_register_id, opened_at);
CREATE INDEX cash_session_user_opened_idx ON cash_session (user_id, opened_at);

CREATE TABLE cash_movement (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cash_session_id     BIGINT         NOT NULL REFERENCES cash_session (id),
    -- DEPOSIT (entrada de efectivo) o WITHDRAWAL (retiro).
    type                VARCHAR(10)    NOT NULL,
    amount              NUMERIC(14,2)  NOT NULL,
    reason              VARCHAR(200)   NOT NULL,
    moved_at            TIMESTAMPTZ    NOT NULL,
    -- Cajero que registró el movimiento.
    user_id             BIGINT         NOT NULL REFERENCES app_user (id),
    -- Quién autorizó el retiro. Vacío en los depósitos.
    authorized_by       BIGINT         REFERENCES app_user (id),
    created_at          TIMESTAMPTZ    NOT NULL,
    created_by          VARCHAR(50)    NOT NULL,
    updated_at          TIMESTAMPTZ    NOT NULL,
    updated_by          VARCHAR(50)    NOT NULL,
    version             INT            NOT NULL DEFAULT 0,
    CONSTRAINT cash_movement_type_ck CHECK (type IN ('DEPOSIT', 'WITHDRAWAL')),
    CONSTRAINT cash_movement_amount_ck CHECK (amount > 0),
    CONSTRAINT cash_movement_reason_ck CHECK (btrim(reason) <> '')
);

CREATE INDEX cash_movement_session_idx ON cash_movement (cash_session_id, id);
