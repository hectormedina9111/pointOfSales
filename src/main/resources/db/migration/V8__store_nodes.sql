-- V8: alta de tiendas (store_node) y datos de activación de la tienda (store_identity).
--
-- Ver docs/plan.md, secciones "Sincronización" y "Alta de tiendas y réplica de datos maestros", y
-- "Decisiones de implementación: paso 6A (alta de tiendas)".
--   * La central no es una fila de store_node: el nodo 0 es la propia central y su rango (1 a 999 999 999)
--     está fijo en el código. store_node solo guarda las tiendas.
--   * store_identity existe solo en el servidor de una tienda, con una única fila: quién es la tienda
--     y con qué credencial habla con la central. Ver la decisión sobre el token en el plan.

CREATE TABLE store_node (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Número de la tienda: 1, 2, 3... Define su rango de ids (node_number * 1 000 000 000 + 1).
    node_number             SMALLINT     NOT NULL UNIQUE CHECK (node_number >= 1),
    -- Sucursal que atiende la tienda. Opcional, pero una sucursal tiene como máximo una tienda.
    branch_id               BIGINT       UNIQUE REFERENCES branch (id),
    id_range_start          BIGINT       NOT NULL,
    id_range_end            BIGINT       NOT NULL,
    -- PENDING: aún no se ha activado. ACTIVE: activada. OUT_OF_SYNC: reservado para el latido.
    -- DISABLED: revocada por la central.
    status                  VARCHAR(15)  NOT NULL CHECK (status IN ('PENDING', 'ACTIVE', 'OUT_OF_SYNC', 'DISABLED')),
    -- SHA-256 en hexadecimal del código de activación de un solo uso. Se borra al canjearlo.
    activation_code_hash    VARCHAR(64)  UNIQUE,
    activation_expires_at   TIMESTAMPTZ,
    -- SHA-256 en hexadecimal del token permanente de la tienda. Nunca se guarda el token en claro aquí.
    credential_hash         VARCHAR(64)  UNIQUE,
    activated_at            TIMESTAMPTZ,
    credential_revoked_at   TIMESTAMPTZ,
    last_heartbeat_at       TIMESTAMPTZ,
    last_download_version   BIGINT,
    last_upload_at          TIMESTAMPTZ,
    app_version             VARCHAR(20),
    pending_upload_count    INT          NOT NULL DEFAULT 0,
    oldest_pending_at       TIMESTAMPTZ,
    created_at              TIMESTAMPTZ  NOT NULL,
    created_by              VARCHAR(50)  NOT NULL,
    updated_at              TIMESTAMPTZ  NOT NULL,
    updated_by              VARCHAR(50)  NOT NULL,
    version                 INT          NOT NULL DEFAULT 0,
    CONSTRAINT store_node_range_ck CHECK (id_range_end > id_range_start)
);

-- Tabla local de la tienda: su identidad frente a la central. Una sola fila.
-- Sin clave foránea a store_node ni a branch: en esta versión esas tablas llegan por replicación
-- (paso siguiente), así que todavía pueden no existir en la base local de la tienda.
CREATE TABLE store_identity (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Id de la fila store_node en la central.
    store_node_id           BIGINT       NOT NULL,
    node_number             SMALLINT     NOT NULL CHECK (node_number >= 1),
    branch_id               BIGINT,
    id_range_start          BIGINT       NOT NULL,
    id_range_end            BIGINT       NOT NULL,
    central_url             VARCHAR(300) NOT NULL,
    -- Token permanente de la tienda en claro: la tienda lo necesita para llamar a la central.
    -- Esta base de datos vive solo en el servidor de la tienda, nunca se replica ni se expone.
    store_token             VARCHAR(100) NOT NULL,
    activated_at            TIMESTAMPTZ  NOT NULL,
    -- Última versión de sync_change_log aplicada (paso de réplica).
    last_applied_version    BIGINT       NOT NULL DEFAULT 0,
    -- Momento en que terminó la carga inicial completa (paso de réplica).
    snapshot_completed_at   TIMESTAMPTZ,
    created_at              TIMESTAMPTZ  NOT NULL,
    created_by              VARCHAR(50)  NOT NULL,
    updated_at              TIMESTAMPTZ  NOT NULL,
    updated_by              VARCHAR(50)  NOT NULL,
    version                 INT          NOT NULL DEFAULT 0,
    CONSTRAINT store_identity_range_ck CHECK (id_range_end > id_range_start)
);
