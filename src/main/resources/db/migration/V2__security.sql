-- V2: seguridad (roles, usuarios, tokens de refresco).
--
-- Ver CLAUDE.md, sección Base de datos. Privilegios (tabla privilege) y sucursales
-- (user_branch) llegan en pasos posteriores.

CREATE TABLE role (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(30)  NOT NULL UNIQUE,
    name        VARCHAR(80)  NOT NULL,
    description VARCHAR(150),
    created_at  TIMESTAMPTZ  NOT NULL,
    created_by  VARCHAR(50)  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL,
    updated_by  VARCHAR(50)  NOT NULL,
    version     INT          NOT NULL DEFAULT 0
);

CREATE TABLE app_user (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_code          VARCHAR(50) UNIQUE,
    username               VARCHAR(50)  NOT NULL UNIQUE,
    password_hash          VARCHAR(255) NOT NULL,
    full_name              VARCHAR(150) NOT NULL,
    email                  VARCHAR(150) UNIQUE,
    authorization_pin_hash VARCHAR(255),
    failed_attempts        SMALLINT     NOT NULL DEFAULT 0,
    locked_until           TIMESTAMPTZ,
    must_change_password   BOOLEAN      NOT NULL DEFAULT TRUE,
    last_login_at          TIMESTAMPTZ,
    active                 BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at             TIMESTAMPTZ  NOT NULL,
    created_by             VARCHAR(50)  NOT NULL,
    updated_at             TIMESTAMPTZ  NOT NULL,
    updated_by             VARCHAR(50)  NOT NULL,
    version                INT          NOT NULL DEFAULT 0
);

CREATE TABLE user_role (
    user_id BIGINT NOT NULL REFERENCES app_user (id),
    role_id BIGINT NOT NULL REFERENCES role (id),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE refresh_token (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES app_user (id),
    token_hash  VARCHAR(64)  NOT NULL UNIQUE,
    expires_at  TIMESTAMPTZ  NOT NULL,
    revoked_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL,
    created_by  VARCHAR(50)  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL,
    updated_by  VARCHAR(50)  NOT NULL,
    version     INT          NOT NULL DEFAULT 0
);

CREATE INDEX refresh_token_user_id_idx ON refresh_token (user_id);

