-- V18: devoluciones y notas de crédito en la tienda (paso 1 del MVP 3B).
--
-- Ver docs/plan.md, "MVP 3B" y "Decisiones de implementación: 3B paso 1". Desviaciones:
--   * sale.type, sale_line.returned_quantity, sale_line.original_line_id y sale_line.restock ya existían en V14
--     (preparados para este paso). Aquí solo se limita el tipo a SALE o RETURN y se quita la llave foránea de
--     original_line_id: en el paso 3 una devolución apunta a una venta de otra tienda que no está en esta base.
--   * sale.refund_method es obligatorio en RETURN, como dice el modelo de datos del plan.
--   * credit_note tiene UNIQUE (return_sale_id): una devolución emite a lo sumo una nota de crédito.
--   * La réplica no toca estas tablas: son documentos de la tienda y suben a la central (sync_outbox).

-- Tipo de documento: venta o devolución.
ALTER TABLE sale ADD CONSTRAINT sale_type_ck CHECK (type IN ('SALE', 'RETURN'));
CREATE INDEX sale_type_idx ON sale (type);

-- Venta que se devuelve. Sin llave foránea: puede ser una venta de otra tienda (paso 3).
ALTER TABLE sale ADD COLUMN original_sale_id BIGINT;
CREATE INDEX sale_original_sale_idx ON sale (original_sale_id);
-- Recibo de la venta original, copiado para imprimir sin buscarla.
ALTER TABLE sale ADD COLUMN original_receipt_number VARCHAR(30);

-- Motivo de la devolución y forma de reembolso: efectivo, método original o nota de crédito.
ALTER TABLE sale ADD COLUMN reason VARCHAR(300);
ALTER TABLE sale ADD COLUMN refund_method VARCHAR(20);
ALTER TABLE sale ADD CONSTRAINT sale_refund_method_ck
    CHECK (refund_method IS NULL OR refund_method IN ('CASH', 'ORIGINAL_METHOD', 'CREDIT_NOTE'));

-- Jefe de tienda que autorizó la devolución (el propio usuario si tiene el privilegio).
ALTER TABLE sale ADD COLUMN return_authorized_by BIGINT REFERENCES app_user (id);

-- Una devolución siempre tiene motivo, venta original y forma de reembolso.
ALTER TABLE sale ADD CONSTRAINT sale_return_ck CHECK (type <> 'RETURN'
    OR (reason IS NOT NULL AND original_sale_id IS NOT NULL AND refund_method IS NOT NULL));

-- Estados de la venta original: devuelta en parte o del todo.
ALTER TABLE sale DROP CONSTRAINT sale_status_ck;
ALTER TABLE sale ADD CONSTRAINT sale_status_ck
    CHECK (status IN ('ON_HOLD', 'PAID', 'PARTIALLY_RETURNED', 'RETURNED'));

-- La línea original puede estar en otra tienda: sin llave foránea (ver la cabecera).
ALTER TABLE sale_line DROP CONSTRAINT sale_line_original_line_id_fkey;
CREATE INDEX sale_line_original_idx ON sale_line (original_line_id);

-- Correlativos por tipo de documento: cada caja tiene su secuencia de ventas, de devoluciones y de notas de crédito.
ALTER TABLE cash_register_counter ADD COLUMN document_type VARCHAR(20) NOT NULL DEFAULT 'SALE';
ALTER TABLE cash_register_counter ADD CONSTRAINT cash_register_counter_document_ck
    CHECK (document_type IN ('SALE', 'RETURN', 'CREDIT_NOTE'));
ALTER TABLE cash_register_counter DROP CONSTRAINT cash_register_counter_pkey;
ALTER TABLE cash_register_counter ADD PRIMARY KEY (cash_register_id, document_type);

-- Nota de crédito: saldo a favor del cliente, emitido por una devolución posterior al día de la venta.
-- El saldo se usa en el paso 2; aquí solo se emite.
CREATE TABLE credit_note (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number              VARCHAR(30)    NOT NULL UNIQUE,
    customer_id         BIGINT         NOT NULL REFERENCES customer (id),
    return_sale_id      BIGINT         NOT NULL REFERENCES sale (id),
    branch_id           BIGINT         NOT NULL REFERENCES branch (id),
    amount              NUMERIC(14,2)  NOT NULL,
    balance             NUMERIC(14,2)  NOT NULL,
    status              VARCHAR(10)    NOT NULL DEFAULT 'ACTIVE',
    issued_at           TIMESTAMPTZ    NOT NULL,
    -- Cuándo llegó a la central; NULL mientras está pendiente de subir.
    synced_at           TIMESTAMPTZ,
    created_at          TIMESTAMPTZ    NOT NULL,
    created_by          VARCHAR(50)    NOT NULL,
    updated_at          TIMESTAMPTZ    NOT NULL,
    updated_by          VARCHAR(50)    NOT NULL,
    version             INT            NOT NULL DEFAULT 0,
    CONSTRAINT credit_note_amount_ck CHECK (amount > 0),
    CONSTRAINT credit_note_balance_ck CHECK (balance >= 0 AND balance <= amount),
    CONSTRAINT credit_note_status_ck CHECK (status IN ('ACTIVE', 'USED')),
    CONSTRAINT credit_note_return_uk UNIQUE (return_sale_id)
);

CREATE INDEX credit_note_customer_idx ON credit_note (customer_id);
CREATE INDEX credit_note_status_idx ON credit_note (status);
