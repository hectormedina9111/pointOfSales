-- V4: organización (país, empresa, sucursal) y sucursales asignadas a usuarios.
--
-- Ver docs/plan.md, sección "Organización". Las columnas CHAR(n) del plan se escriben como
-- VARCHAR(n): ddl-auto=validate compara tipos y VARCHAR coincide con los campos String de JPA.

CREATE TABLE country (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iso_code      VARCHAR(2)   NOT NULL UNIQUE,
    name          VARCHAR(80)  NOT NULL,
    currency      VARCHAR(3)   NOT NULL,
    time_zone     VARCHAR(50)  NOT NULL,
    tax_id_label  VARCHAR(20)  NOT NULL,
    fiscal_provider VARCHAR(30) NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL,
    created_by    VARCHAR(50)  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL,
    updated_by    VARCHAR(50)  NOT NULL,
    version       INT          NOT NULL DEFAULT 0
);

CREATE TABLE company (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legal_name  VARCHAR(200) NOT NULL,
    trade_name  VARCHAR(200),
    tax_id      VARCHAR(14)  NOT NULL UNIQUE,
    address     VARCHAR(300),
    phone       VARCHAR(20),
    email       VARCHAR(150),
    currency    VARCHAR(3)   NOT NULL DEFAULT 'HNL',
    time_zone   VARCHAR(50)  NOT NULL DEFAULT 'America/Tegucigalpa',
    created_at  TIMESTAMPTZ  NOT NULL,
    created_by  VARCHAR(50)  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL,
    updated_by  VARCHAR(50)  NOT NULL,
    version     INT          NOT NULL DEFAULT 0
);

CREATE TABLE branch (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id              BIGINT       NOT NULL REFERENCES company (id),
    code                    VARCHAR(10)  NOT NULL UNIQUE,
    name                    VARCHAR(120) NOT NULL,
    address                 VARCHAR(300),
    phone                   VARCHAR(20),
    allow_negative_stock    BOOLEAN      NOT NULL DEFAULT FALSE,
    active                  BOOLEAN      NOT NULL DEFAULT TRUE,
    country_id              BIGINT       NOT NULL REFERENCES country (id),
    -- La clave foránea hacia price_list se agrega en el paso 5 (listas de precios).
    default_price_list_id   BIGINT,
    created_at              TIMESTAMPTZ  NOT NULL,
    created_by              VARCHAR(50)  NOT NULL,
    updated_at              TIMESTAMPTZ  NOT NULL,
    updated_by              VARCHAR(50)  NOT NULL,
    version                 INT          NOT NULL DEFAULT 0
);

CREATE INDEX branch_country_id_idx ON branch (country_id);

-- Sucursales que puede ver cada usuario. Sin asignación, el usuario no ve ninguna sucursal.
CREATE TABLE user_branch (
    user_id   BIGINT NOT NULL REFERENCES app_user (id),
    branch_id BIGINT NOT NULL REFERENCES branch (id),
    PRIMARY KEY (user_id, branch_id)
);

CREATE INDEX user_branch_branch_id_idx ON user_branch (branch_id);
