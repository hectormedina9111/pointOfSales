-- V22: inventario, paso 3 (seriales). Ver docs/plan.md, "MVP 4: inventario" y "Decisiones de implementación: inventario
-- paso 3 (seriales)".
--   * product_serial es una fila por unidad física de un producto con tracks_serials. Un número de serie es único por
--     producto en todo el sistema; la central junta las filas de las tiendas por (producto, número) y no por id.
--   * inventory_movement_serial liga cada movimiento con los seriales que movió (trazabilidad).
--   * sale_line_serial guarda solo el número de serie de cada línea de venta o devolución. No tiene llave foránea a
--     inventario: los módulos no comparten tablas.

CREATE TABLE product_serial (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id         BIGINT        NOT NULL REFERENCES product (id),
    serial_number      VARCHAR(100)  NOT NULL,
    -- Sucursal donde está ahora (o donde estaba por última vez si ya salió).
    branch_id          BIGINT        NOT NULL REFERENCES branch (id),
    status             VARCHAR(15)   NOT NULL CHECK (status IN ('AVAILABLE', 'SOLD', 'IN_TRANSIT', 'REMOVED')),
    received_at        TIMESTAMPTZ   NOT NULL,
    -- Última venta del serial. Sin llave foránea: la venta puede vivir en otro nodo.
    sold_at            TIMESTAMPTZ,
    last_sale_id       BIGINT,
    -- Movimiento con el que entró a la sucursal actual. Sin llave foránea por la misma razón.
    entry_movement_id  BIGINT,
    -- Momento en que la central recibió la fila; NULL mientras está solo en la tienda.
    synced_at          TIMESTAMPTZ,
    created_at         TIMESTAMPTZ   NOT NULL,
    created_by         VARCHAR(50)   NOT NULL,
    updated_at         TIMESTAMPTZ   NOT NULL,
    updated_by         VARCHAR(50)   NOT NULL,
    version            INT           NOT NULL DEFAULT 0,
    CONSTRAINT product_serial_product_number_uk UNIQUE (product_id, serial_number)
);

CREATE INDEX product_serial_branch_status_idx ON product_serial (branch_id, product_id, status);
CREATE INDEX product_serial_lower_number_idx ON product_serial (lower(serial_number));

-- Los seriales que movió cada movimiento de inventario.
CREATE TABLE inventory_movement_serial (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_id  BIGINT       NOT NULL REFERENCES inventory_movement (id),
    serial_id    BIGINT       NOT NULL REFERENCES product_serial (id),
    created_at   TIMESTAMPTZ  NOT NULL,
    created_by   VARCHAR(50)  NOT NULL,
    updated_at   TIMESTAMPTZ  NOT NULL,
    updated_by   VARCHAR(50)  NOT NULL,
    version      INT          NOT NULL DEFAULT 0,
    CONSTRAINT inventory_movement_serial_uk UNIQUE (movement_id, serial_id)
);

CREATE INDEX inventory_movement_serial_serial_idx ON inventory_movement_serial (serial_id);

-- Los seriales de cada línea de venta o devolución. returned = true en la línea original significa que ya volvió; en una
-- línea de devolución, que esa devolución trae de vuelta el serial.
CREATE TABLE sale_line_serial (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_line_id   BIGINT       NOT NULL REFERENCES sale_line (id),
    serial_number  VARCHAR(100) NOT NULL,
    returned       BOOLEAN      NOT NULL DEFAULT false,
    created_at     TIMESTAMPTZ  NOT NULL,
    created_by     VARCHAR(50)  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    updated_by     VARCHAR(50)  NOT NULL,
    version        INT          NOT NULL DEFAULT 0,
    CONSTRAINT sale_line_serial_line_number_uk UNIQUE (sale_line_id, serial_number)
);

CREATE INDEX sale_line_serial_number_idx ON sale_line_serial (lower(serial_number));
