-- V3: privilegios (tabla privilege) y su asignación a roles (role_privilege).
--
-- Ver docs/plan.md, sección privilege. Los ENDPOINT no se siembran aquí: los registra
-- el arranque de la aplicación leyendo los controladores (EndpointPrivilegeRegistrar).

CREATE TABLE privilege (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(80)  NOT NULL UNIQUE,
    type           VARCHAR(10)  NOT NULL CHECK (type IN ('ENDPOINT', 'MENU', 'ACTION')),
    name           VARCHAR(120) NOT NULL,
    description    VARCHAR(300),
    module         VARCHAR(30)  NOT NULL,
    http_method    VARCHAR(7),
    path_pattern   VARCHAR(200),
    parent_id      BIGINT REFERENCES privilege (id),
    frontend_route VARCHAR(200),
    icon           VARCHAR(50),
    sort_order     SMALLINT     NOT NULL DEFAULT 0,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL,
    created_by     VARCHAR(50)  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    updated_by     VARCHAR(50)  NOT NULL,
    version        INT          NOT NULL DEFAULT 0,
    CONSTRAINT privilege_method_path_uk UNIQUE (http_method, path_pattern),
    CONSTRAINT privilege_endpoint_route_chk CHECK (
        type <> 'ENDPOINT' OR (http_method IS NOT NULL AND path_pattern IS NOT NULL)),
    CONSTRAINT privilege_non_endpoint_route_chk CHECK (
        type = 'ENDPOINT' OR (http_method IS NULL AND path_pattern IS NULL))
);

CREATE TABLE role_privilege (
    role_id      BIGINT       NOT NULL REFERENCES role (id),
    privilege_id BIGINT       NOT NULL REFERENCES privilege (id),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by   VARCHAR(50)  NOT NULL DEFAULT 'system',
    PRIMARY KEY (role_id, privilege_id)
);

CREATE INDEX role_privilege_privilege_id_idx ON role_privilege (privilege_id);

