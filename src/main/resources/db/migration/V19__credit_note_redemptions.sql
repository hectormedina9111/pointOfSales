-- V19: saldo de las notas de crédito en la central y pago con nota de crédito (paso 2 del MVP 3B).
--
-- Ver docs/plan.md, "MVP 3B" y "Decisiones de implementación: 3B paso 2 (notas de crédito)". Desviaciones:
--   * credit_note se replica a todas las tiendas, como customer: cada tienda ve todas las notas y su saldo para los
--     listados. El saldo que se muestra en una tienda puede tener unos segundos de atraso; cobrar siempre consulta la
--     central, que es la única que descuenta.
--   * return_sale_id conserva su clave foránea. La réplica escribe con session_replication_role = replica, que no revisa
--     claves foráneas, así que una tienda puede recibir una nota cuya venta de origen no tiene.
--   * El método de pago CREDIT_NOTE no se inserta aquí: lo crea el sembrado de la central (PaymentMethodSeeder), que
--     después llega a las tiendas por la réplica de payment_method.
--   * credit_note_redemption solo existe en la central y no tiene disparador de réplica.
--   * payment.credit_note_id no tiene clave foránea: la nota se valida en la central antes de cobrar, y la tienda puede
--     tener el pago antes que su réplica de la nota.

-- Réplica de las notas: mismo disparador que las demás tablas principales (ver V9 y V12).
CREATE TRIGGER sync_log_credit_note AFTER INSERT OR UPDATE OR DELETE ON credit_note
    FOR EACH ROW EXECUTE FUNCTION sync_log_change('credit_note', 'id', 'main');

-- Carga inicial: las notas que ya existen se envían a las tiendas en la próxima sincronización (ver V9).
INSERT INTO sync_change_log (entity, entity_id, operation) SELECT 'credit_note', id, 'UPSERT' FROM credit_note;

-- Cada descuento de saldo que la central aplica a un pago. Vive solo en la central.
-- APPLIED: el saldo ya se descontó. CONFIRMED: la venta que la usó llegó a la central. RELEASED: el pago falló y el
-- monto volvió al saldo.
CREATE TABLE credit_note_redemption (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credit_note_id  BIGINT        NOT NULL REFERENCES credit_note (id),
    -- Número de idempotencia del pago: "{clave del cobro}:{posición del pago}". Único en toda la central.
    redemption_key  VARCHAR(100)  NOT NULL UNIQUE,
    amount          NUMERIC(14,2) NOT NULL,
    -- Tienda que descontó el saldo. Sin clave foránea: la tienda es un nodo, no una fila de esta base.
    store_node_id   BIGINT        NOT NULL,
    -- Venta que usó la nota; NULL hasta que la venta sube a la central.
    sale_id         BIGINT,
    status          VARCHAR(10)   NOT NULL,
    created_at      TIMESTAMPTZ   NOT NULL,
    created_by      VARCHAR(50)   NOT NULL,
    updated_at      TIMESTAMPTZ   NOT NULL,
    updated_by      VARCHAR(50)   NOT NULL,
    version         INT           NOT NULL DEFAULT 0,
    CONSTRAINT credit_note_redemption_amount_ck CHECK (amount > 0),
    CONSTRAINT credit_note_redemption_status_ck CHECK (status IN ('APPLIED', 'CONFIRMED', 'RELEASED'))
);

CREATE INDEX credit_note_redemption_note_idx ON credit_note_redemption (credit_note_id);

-- Pago con nota de crédito: la nota y la clave de su descuento. Sin claves foráneas (ver la cabecera).
ALTER TABLE payment ADD COLUMN credit_note_id BIGINT;
ALTER TABLE payment ADD COLUMN redemption_key VARCHAR(100);
