-- V24: equipos (serie con características y código externo). Ver docs/plan.md, "MVP 4: inventario" y
-- "Decisiones de implementación: inventario paso 9 (equipos)".
--   * category_attribute es la plantilla de características de una categoría. Es dato maestro: vive en la central y se
--     replica a las tiendas con disparador propio, como category.
--   * product_serial (el equipo) gana el código externo, las características en JSONB y la categoría copiada del
--     producto, para que el filtro por categoría se resuelva en la base de datos.
--   * La fila de transferencia por serie lleva el código externo y las características para crear el equipo en la
--     tienda destino.

-- Plantilla de características por categoría.
CREATE TABLE category_attribute (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id  BIGINT       NOT NULL REFERENCES category (id),
    -- Clave técnica: letras minúsculas, dígitos y guion bajo. No cambia después de crearla.
    code         VARCHAR(40)  NOT NULL CHECK (code ~ '^[a-z0-9_]+$'),
    name         VARCHAR(80)  NOT NULL,
    data_type    VARCHAR(10)  NOT NULL CHECK (data_type IN ('TEXT', 'NUMBER', 'DATE', 'LIST')),
    -- Opciones de una lista: arreglo de textos. Obligatorio cuando el tipo es LIST.
    options      JSONB,
    required     BOOLEAN      NOT NULL DEFAULT FALSE,
    sort_order   INT          NOT NULL DEFAULT 0,
    active       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ  NOT NULL,
    created_by   VARCHAR(50)  NOT NULL,
    updated_at   TIMESTAMPTZ  NOT NULL,
    updated_by   VARCHAR(50)  NOT NULL,
    version      INT          NOT NULL DEFAULT 0,
    CONSTRAINT category_attribute_category_code_uk UNIQUE (category_id, code),
    CONSTRAINT category_attribute_options_ck CHECK (
        (data_type = 'LIST' AND options IS NOT NULL AND jsonb_typeof(options) = 'array'
            AND jsonb_array_length(options) > 0)
        OR (data_type <> 'LIST' AND options IS NULL))
);

-- Réplica: entidad principal, como category (ver V9).
CREATE TRIGGER sync_log_category_attribute AFTER INSERT OR UPDATE OR DELETE ON category_attribute
    FOR EACH ROW EXECUTE FUNCTION sync_log_change('category_attribute', 'id', 'main');

-- Equipo: código externo (opcional, único cuando tiene valor) y características validadas contra la plantilla.
ALTER TABLE product_serial ADD COLUMN external_code VARCHAR(50);
ALTER TABLE product_serial ADD CONSTRAINT product_serial_external_code_ck CHECK (
    external_code IS NULL OR btrim(external_code) <> '');
CREATE UNIQUE INDEX product_serial_external_code_uk ON product_serial (external_code) WHERE external_code IS NOT NULL;
ALTER TABLE product_serial ADD COLUMN attributes JSONB NOT NULL DEFAULT '{}'::jsonb;
-- Categoría del producto al crear el equipo. Sin llave foránea a la lectura de catálogo: solo es la copia de filtro.
ALTER TABLE product_serial ADD COLUMN category_id BIGINT REFERENCES category (id);

-- Relleno de los equipos existentes con la categoría que guardan las copias de existencia de su producto.
UPDATE product_serial ps
   SET category_id = copy.category_id
  FROM (SELECT product_id, MAX(category_id) AS category_id
          FROM inventory_item
         WHERE category_id IS NOT NULL
         GROUP BY product_id) copy
 WHERE copy.product_id = ps.product_id;

CREATE INDEX product_serial_category_status_idx ON product_serial (category_id, status);

-- La serie de transferencia lleva los datos del equipo para crearlo en la tienda destino.
ALTER TABLE inventory_transfer_line_serial ADD COLUMN external_code VARCHAR(50);
ALTER TABLE inventory_transfer_line_serial ADD COLUMN attributes JSONB NOT NULL DEFAULT '{}'::jsonb;
