-- V11: cambio de contraseña en la tienda y subidas de la tienda a la central.
--
-- Ver docs/plan.md, "Decisiones de implementación: cambio de contraseña en la tienda".
--   * app_user.password_changed_at: momento del último cambio de contraseña. Decide qué cambio gana
--     (el más reciente) cuando la central recibe una contraseña cambiada en una tienda.
--   * sync_outbox (solo en la tienda): cola de envíos pendientes hacia la central. Es de solo anexar:
--     no tiene columnas de auditoría; cada fila se marca como enviada, nunca se borra.
--   * sync_upload_receipt (solo en la central): recibo de cada envío aceptado o rechazado, para no
--     aplicar dos veces el mismo envío de una tienda.
--   * Ninguna de estas tablas está en el registro de replicación (SyncTables): no viajan a las tiendas.

ALTER TABLE app_user ADD COLUMN password_changed_at TIMESTAMPTZ;

CREATE TABLE sync_outbox (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Tipo de envío, por ejemplo PASSWORD_CHANGED.
    event_type      VARCHAR(40)  NOT NULL,
    -- Datos del envío en JSON. Para una contraseña: el hash, nunca la contraseña en claro.
    payload         JSONB        NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL,
    -- Momento en que la central respondió (aceptado o rechazado). NULL mientras está pendiente.
    uploaded_at     TIMESTAMPTZ,
    attempts        INT          NOT NULL DEFAULT 0,
    -- Último error de envío o código de respuesta de la central (por ejemplo STALE).
    last_error      VARCHAR(500),
    result          VARCHAR(20)  CHECK (result IN ('ACCEPTED', 'REJECTED'))
);

CREATE INDEX sync_outbox_pending_idx ON sync_outbox (uploaded_at) WHERE uploaded_at IS NULL;

CREATE TABLE sync_upload_receipt (
    -- Tienda que envió el registro (store_node.id en la central). Sin clave foránea: el recibo es histórico.
    store_node_id   BIGINT       NOT NULL,
    -- Id del registro en sync_outbox de la tienda.
    outbox_id       BIGINT       NOT NULL,
    received_at     TIMESTAMPTZ  NOT NULL,
    result          VARCHAR(20)  NOT NULL,
    PRIMARY KEY (store_node_id, outbox_id)
);
