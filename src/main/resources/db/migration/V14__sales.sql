-- V14: ventas en la tienda (paso 3 del MVP 3A).
--
-- Ver docs/plan.md, "Ventas" y "Decisiones de implementación: 3A paso 3". Desviaciones:
--   * sale no tiene customer_id: el módulo de clientes llega después; todas las ventas son de consumidor final.
--   * payment.card_last4 es VARCHAR(4), no CHAR(4), igual que las demás columnas CHAR del modelo (V4).
--   * sale_line.subtotal es la base gravable después de descuento: subtotal + tax_amount = total.
--   * sale_line no tiene índice único por (sale_id, line_number): al cambiar las líneas de una venta en espera,
--     Hibernate inserta antes de borrar y una llave única rechazaría el cambio.
--   * Las tablas son documentos de la tienda: no tienen triggers sync_log_change y suben a la central en el paso 4.
--   * cash_register_counter es el correlativo local de recibos de cada caja; no se replica (ver V12).
--   * sale_internal_number_seq arranca en 1 en cualquier nodo. El ajuste al rango del nodo queda para el paso 4,
--     porque IdRangeSequenceAdjuster solo mueve las columnas identity.

CREATE SEQUENCE sale_internal_number_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE sale (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- SALE (venta). Las devoluciones (RETURN) llegan en el MVP 3B.
    type                    VARCHAR(10)    NOT NULL DEFAULT 'SALE',
    -- Número interno por nodo: existe aunque la venta no se pague.
    internal_number         BIGINT         NOT NULL UNIQUE,
    -- Recibo: prefijo de la caja más correlativo de 8 dígitos. Se asigna al cobrar.
    receipt_number          VARCHAR(40)    UNIQUE,
    -- TICKET en 3A; sin CAI hasta la facturación fiscal (3C).
    document_type           VARCHAR(20)    NOT NULL DEFAULT 'TICKET',
    branch_id               BIGINT         NOT NULL REFERENCES branch (id),
    cash_register_id        BIGINT         NOT NULL REFERENCES cash_register (id),
    cash_session_id         BIGINT         NOT NULL REFERENCES cash_session (id),
    -- Cajero que armó y cobró la venta.
    cashier_id              BIGINT         NOT NULL REFERENCES app_user (id),
    -- ON_HOLD (en espera, sin cobrar) o PAID (cobrada).
    status                  VARCHAR(20)    NOT NULL,
    -- true si contiene un producto de factura exclusiva.
    is_exclusive            BOOLEAN        NOT NULL DEFAULT FALSE,
    -- Base gravable de los precios antes de descuento.
    subtotal                NUMERIC(14,2)  NOT NULL,
    -- Suma de los descuentos de línea y de venta, con impuesto incluido.
    discount_total          NUMERIC(14,2)  NOT NULL DEFAULT 0,
    -- Desglose fiscal: base de lo exento y base gravada al 15 % y al 18 %.
    exempt_amount           NUMERIC(14,2)  NOT NULL DEFAULT 0,
    taxable_amount_15       NUMERIC(14,2)  NOT NULL DEFAULT 0,
    taxable_amount_18       NUMERIC(14,2)  NOT NULL DEFAULT 0,
    tax_total               NUMERIC(14,2)  NOT NULL,
    total                   NUMERIC(14,2)  NOT NULL,
    amount_paid             NUMERIC(14,2)  NOT NULL DEFAULT 0,
    change_due              NUMERIC(14,2)  NOT NULL DEFAULT 0,
    paid_at                 TIMESTAMPTZ,
    -- Descuento de la venta completa, tal como lo pidió el cajero.
    discount_type           VARCHAR(10),
    discount_value          NUMERIC(14,2),
    -- Quién autorizó un descuento mayor al máximo permitido (el propio cajero si tiene el privilegio).
    discount_authorized_by  BIGINT         REFERENCES app_user (id),
    notes                   VARCHAR(500),
    -- Clave de idempotencia del cobro: repetirla devuelve la misma venta y no crea otra.
    idempotency_key         VARCHAR(64)    UNIQUE,
    fiscal_status           VARCHAR(15)    NOT NULL DEFAULT 'NOT_REQUIRED',
    fiscal_number           VARCHAR(30)    UNIQUE,
    -- Datos propios del país para imprimir (CAI, QR, etc.); vacío sin facturación fiscal.
    fiscal_data             JSONB,
    -- Cuándo llegó la venta a la central; NULL mientras está pendiente de subir.
    synced_at               TIMESTAMPTZ,
    created_at              TIMESTAMPTZ    NOT NULL,
    created_by              VARCHAR(50)    NOT NULL,
    updated_at              TIMESTAMPTZ    NOT NULL,
    updated_by              VARCHAR(50)    NOT NULL,
    version                 INT            NOT NULL DEFAULT 0,
    CONSTRAINT sale_status_ck CHECK (status IN ('ON_HOLD', 'PAID')),
    CONSTRAINT sale_discount_type_ck CHECK (discount_type IS NULL OR discount_type IN ('AMOUNT', 'PERCENTAGE')),
    CONSTRAINT sale_discount_value_ck CHECK (discount_value IS NULL OR discount_value >= 0),
    CONSTRAINT sale_total_ck CHECK (total >= 0),
    -- Una venta cobrada tiene recibo y fecha de cobro; una en espera no.
    CONSTRAINT sale_paid_ck CHECK (status = 'ON_HOLD' OR (receipt_number IS NOT NULL AND paid_at IS NOT NULL))
);

-- Listados por sucursal, por caja y estado (holds de una caja), por sesión y por cajero.
CREATE INDEX sale_branch_created_idx ON sale (branch_id, created_at);
CREATE INDEX sale_register_status_idx ON sale (cash_register_id, status);
CREATE INDEX sale_session_status_idx ON sale (cash_session_id, status);
CREATE INDEX sale_cashier_created_idx ON sale (cashier_id, created_at);

CREATE TABLE sale_line (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id             BIGINT         NOT NULL REFERENCES sale (id),
    -- Orden en el ticket, empezando en 1.
    line_number         SMALLINT       NOT NULL,
    product_id          BIGINT         NOT NULL REFERENCES product (id),
    -- Copias históricas del producto al vender.
    sku                 VARCHAR(40)    NOT NULL,
    description         VARCHAR(200)   NOT NULL,
    quantity            NUMERIC(12,3)  NOT NULL,
    -- Precio vigente al vender, con impuesto incluido.
    unit_price          NUMERIC(14,2)  NOT NULL,
    unit_cost           NUMERIC(14,2),
    -- Descuento de la línea, tal como lo pidió el cajero.
    discount_type       VARCHAR(10),
    discount_value      NUMERIC(14,2)  DEFAULT 0,
    -- Descuento total aplicado a la línea: el de línea más la parte del descuento de venta.
    discount_amount     NUMERIC(14,2)  NOT NULL DEFAULT 0,
    tax_code            VARCHAR(20)    NOT NULL,
    tax_rate            NUMERIC(5,2)   NOT NULL,
    tax_amount          NUMERIC(14,2)  NOT NULL,
    subtotal            NUMERIC(14,2)  NOT NULL,
    total               NUMERIC(14,2)  NOT NULL,
    -- Para el MVP 3B (devoluciones): sin uso en 3A.
    returned_quantity   NUMERIC(12,3)  NOT NULL DEFAULT 0,
    original_line_id    BIGINT         REFERENCES sale_line (id),
    restock             BOOLEAN,
    -- Lista de la que salió el precio; NULL cuando se usó el precio base del producto.
    price_list_id       BIGINT         REFERENCES price_list (id),
    created_at          TIMESTAMPTZ    NOT NULL,
    created_by          VARCHAR(50)    NOT NULL,
    updated_at          TIMESTAMPTZ    NOT NULL,
    updated_by          VARCHAR(50)    NOT NULL,
    version             INT            NOT NULL DEFAULT 0,
    CONSTRAINT sale_line_quantity_ck CHECK (quantity > 0),
    CONSTRAINT sale_line_discount_type_ck CHECK (discount_type IS NULL OR discount_type IN ('AMOUNT', 'PERCENTAGE')),
    CONSTRAINT sale_line_returned_ck CHECK (returned_quantity >= 0 AND returned_quantity <= quantity)
);

CREATE INDEX sale_line_sale_idx ON sale_line (sale_id, line_number);
CREATE INDEX sale_line_product_idx ON sale_line (product_id);

CREATE TABLE payment (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id             BIGINT         NOT NULL REFERENCES sale (id),
    payment_method_id   BIGINT         NOT NULL REFERENCES payment_method (id),
    -- Monto aplicado a la venta. En efectivo es neto de vuelto.
    amount              NUMERIC(14,2)  NOT NULL,
    -- Efectivo entregado por el cliente; solo en métodos que dan vuelto.
    amount_received     NUMERIC(14,2),
    -- Autorización de la tarjeta o número de transferencia.
    reference           VARCHAR(60),
    -- Últimos cuatro dígitos de la tarjeta. El número completo nunca se guarda.
    card_last4          VARCHAR(4),
    paid_at             TIMESTAMPTZ    NOT NULL,
    created_at          TIMESTAMPTZ    NOT NULL,
    created_by          VARCHAR(50)    NOT NULL,
    updated_at          TIMESTAMPTZ    NOT NULL,
    updated_by          VARCHAR(50)    NOT NULL,
    version             INT            NOT NULL DEFAULT 0,
    CONSTRAINT payment_amount_ck CHECK (amount > 0),
    CONSTRAINT payment_received_ck CHECK (amount_received IS NULL OR amount_received >= amount),
    CONSTRAINT payment_card_last4_ck CHECK (card_last4 IS NULL OR card_last4 ~ '^[0-9]{4}$')
);

CREATE INDEX payment_sale_idx ON payment (sale_id);
CREATE INDEX payment_method_idx ON payment (payment_method_id);

-- Correlativo de recibos de cada caja, local de la tienda. Se bloquea con FOR UPDATE al cobrar.
CREATE TABLE cash_register_counter (
    cash_register_id    BIGINT         PRIMARY KEY REFERENCES cash_register (id),
    last_number         BIGINT         NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ    NOT NULL,
    created_by          VARCHAR(50)    NOT NULL,
    updated_at          TIMESTAMPTZ    NOT NULL,
    updated_by          VARCHAR(50)    NOT NULL,
    version             INT            NOT NULL DEFAULT 0,
    CONSTRAINT cash_register_counter_last_ck CHECK (last_number >= 0)
);
