-- V23: inventario, paso 4 (transferencias entre sucursales). Ver docs/plan.md, "MVP 4: inventario" y
-- "Decisiones de implementación: inventario paso 4 (transferencias)".
--   * La tienda de origen crea la transferencia con sus líneas y seriales, descuenta (TRANSFER_OUT) y sube el
--     documento a la central. La central la inserta con los mismos ids y sus disparadores la replican a todas las
--     tiendas, como los clientes (V16) y los créditos (V19).
--   * La tienda destino confirma la recepción: actualiza la fila replicada, aplica TRANSFER_IN y sube la confirmación.
--     La central actualiza la transferencia y sus líneas, y sus disparadores la replican de nuevo a todas las tiendas.
--   * Las tres tablas son entidades principales de la réplica (SyncTables.main), cada una con su id de rango.
--   * El contador de números admite el tipo TRANSFER (mismo contador por sucursal de origen que los documentos).

-- Contador de transferencias: mismo contador que los documentos, con un tipo nuevo.
ALTER TABLE inventory_document_counter DROP CONSTRAINT inventory_document_counter_type_check;
ALTER TABLE inventory_document_counter ADD CONSTRAINT inventory_document_counter_type_ck
    CHECK (type IN ('ENTRY', 'EXIT', 'ADJUSTMENT', 'TRANSFER'));

CREATE TABLE inventory_transfer (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Formato TR-{código de sucursal de origen}-{000001}. Único en todo el sistema.
    number                   VARCHAR(30)   NOT NULL UNIQUE,
    origin_branch_id         BIGINT        NOT NULL REFERENCES branch (id),
    destination_branch_id    BIGINT        NOT NULL REFERENCES branch (id),
    status                   VARCHAR(30)   NOT NULL CHECK (status IN ('IN_TRANSIT', 'RECEIVED',
                                                                      'RECEIVED_WITH_DIFFERENCES')),
    notes                    VARCHAR(500),
    sent_at                  TIMESTAMPTZ   NOT NULL,
    sent_by                  BIGINT        NOT NULL REFERENCES app_user (id),
    received_at              TIMESTAMPTZ,
    received_by              BIGINT        REFERENCES app_user (id),
    receive_notes            VARCHAR(500),
    -- Clave de idempotencia del envío y de la recepción. Únicas cuando tienen valor.
    send_idempotency_key     VARCHAR(64)   UNIQUE,
    receive_idempotency_key  VARCHAR(64)   UNIQUE,
    created_at               TIMESTAMPTZ   NOT NULL,
    created_by               VARCHAR(50)   NOT NULL,
    updated_at               TIMESTAMPTZ   NOT NULL,
    updated_by               VARCHAR(50)   NOT NULL,
    version                  INT           NOT NULL DEFAULT 0,
    CONSTRAINT inventory_transfer_branches_ck CHECK (origin_branch_id <> destination_branch_id),
    CONSTRAINT inventory_transfer_received_ck CHECK (status = 'IN_TRANSIT'
        OR (received_at IS NOT NULL AND received_by IS NOT NULL))
);

CREATE INDEX inventory_transfer_origin_idx ON inventory_transfer (origin_branch_id, sent_at);
CREATE INDEX inventory_transfer_destination_idx ON inventory_transfer (destination_branch_id, sent_at);

CREATE TABLE inventory_transfer_line (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id        BIGINT        NOT NULL REFERENCES inventory_transfer (id),
    product_id         BIGINT        NOT NULL REFERENCES product (id),
    -- Cantidad enviada.
    quantity           NUMERIC(12,3) NOT NULL CHECK (quantity > 0),
    -- Cantidad recibida: NULL mientras la transferencia está en tránsito.
    received_quantity  NUMERIC(12,3) CHECK (received_quantity >= 0),
    -- Costo promedio de la sucursal de origen al enviar.
    unit_cost          NUMERIC(14,4) NOT NULL CHECK (unit_cost >= 0),
    created_at         TIMESTAMPTZ   NOT NULL,
    created_by         VARCHAR(50)   NOT NULL,
    updated_at         TIMESTAMPTZ   NOT NULL,
    updated_by         VARCHAR(50)   NOT NULL,
    version            INT           NOT NULL DEFAULT 0,
    CONSTRAINT inventory_transfer_line_product_uk UNIQUE (transfer_id, product_id),
    CONSTRAINT inventory_transfer_line_received_ck CHECK (received_quantity IS NULL
        OR received_quantity <= quantity)
);

-- Seriales enviados en una línea. received indica si la tienda destino los recibió.
CREATE TABLE inventory_transfer_line_serial (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    line_id        BIGINT       NOT NULL REFERENCES inventory_transfer_line (id),
    serial_number  VARCHAR(100) NOT NULL,
    received       BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMPTZ  NOT NULL,
    created_by     VARCHAR(50)  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    updated_by     VARCHAR(50)  NOT NULL,
    version        INT          NOT NULL DEFAULT 0,
    CONSTRAINT inventory_transfer_line_serial_uk UNIQUE (line_id, serial_number)
);

-- Réplica: mismo disparador que las demás entidades principales (ver V9 y V16).
CREATE TRIGGER sync_log_inventory_transfer AFTER INSERT OR UPDATE OR DELETE ON inventory_transfer
    FOR EACH ROW EXECUTE FUNCTION sync_log_change('inventory_transfer', 'id', 'main');
CREATE TRIGGER sync_log_inventory_transfer_line AFTER INSERT OR UPDATE OR DELETE ON inventory_transfer_line
    FOR EACH ROW EXECUTE FUNCTION sync_log_change('inventory_transfer_line', 'id', 'main');
CREATE TRIGGER sync_log_inventory_transfer_line_serial AFTER INSERT OR UPDATE OR DELETE ON inventory_transfer_line_serial
    FOR EACH ROW EXECUTE FUNCTION sync_log_change('inventory_transfer_line_serial', 'id', 'main');
