-- V7: listas de precios y precios por producto y escala.
--
-- Ver docs/plan.md, sección "Listas de precios" y "Reglas de negocio del catálogo" (Resolución de precio).
-- Desviaciones documentadas en "Decisiones de implementación: paso 5 (precios)":
--   * valid_from y valid_to son DATE: la vigencia es un día del calendario, no un instante.
--   * Además de las reglas del plan, la base de datos exige el porcentaje con PERCENT_OFF_BASE
--     y que valid_to no sea anterior a valid_from.

CREATE TABLE price_list (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(30)   NOT NULL UNIQUE,
    name            VARCHAR(100)  NOT NULL,
    -- La moneda sale del país de la lista.
    country_id      BIGINT        NOT NULL REFERENCES country (id),
    -- FIXED_PRICE: precio por producto en price_list_item. PERCENT_OFF_BASE: descuento sobre el precio base.
    pricing_method  VARCHAR(15)   NOT NULL CHECK (pricing_method IN ('FIXED_PRICE', 'PERCENT_OFF_BASE')),
    -- Obligatorio con PERCENT_OFF_BASE. Ejemplo: 10.00 significa 10 % menos que el precio base.
    percent         NUMERIC(5,2)  CHECK (percent IS NULL OR (percent >= 0 AND percent <= 100)),
    -- Vigencia opcional: NULL significa sin límite en ese extremo.
    valid_from      DATE,
    valid_to        DATE,
    -- Desempate si aplican varias listas. La resolución de precio no lo usa todavía.
    priority        SMALLINT      NOT NULL DEFAULT 0,
    active          BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ   NOT NULL,
    created_by      VARCHAR(50)   NOT NULL,
    updated_at      TIMESTAMPTZ   NOT NULL,
    updated_by      VARCHAR(50)   NOT NULL,
    version         INT           NOT NULL DEFAULT 0,
    CONSTRAINT price_list_percent_ck CHECK (pricing_method <> 'PERCENT_OFF_BASE' OR percent IS NOT NULL),
    CONSTRAINT price_list_validity_ck CHECK (valid_from IS NULL OR valid_to IS NULL OR valid_to >= valid_from)
);

CREATE INDEX price_list_country_id_idx ON price_list (country_id);

CREATE TABLE price_list_item (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_list_id   BIGINT        NOT NULL REFERENCES price_list (id),
    product_id      BIGINT        NOT NULL REFERENCES product (id),
    -- Escalas de mayoreo: el precio aplica a partir de esta cantidad.
    min_quantity    NUMERIC(12,3) NOT NULL DEFAULT 1 CHECK (min_quantity >= 1),
    -- Con ISV incluido.
    price           NUMERIC(14,2) NOT NULL CHECK (price >= 0),
    created_at      TIMESTAMPTZ   NOT NULL,
    created_by      VARCHAR(50)   NOT NULL,
    updated_at      TIMESTAMPTZ   NOT NULL,
    updated_by      VARCHAR(50)   NOT NULL,
    version         INT           NOT NULL DEFAULT 0,
    -- Una sola escala por producto y lista. La clave también sirve de índice por lista.
    CONSTRAINT price_list_item_scale_uk UNIQUE (price_list_id, product_id, min_quantity)
);

CREATE INDEX price_list_item_product_id_idx ON price_list_item (product_id);

