-- V20: devoluciones de ventas de otra sucursal y reservas en la central (paso 3 del MVP 3B).
--
-- Ver docs/plan.md, "MVP 3B" y "Decisiones de implementación: 3B paso 3 (reservas y devoluciones en otra sucursal)".
-- Desviaciones:
--   * sale_return_claim se replica a todas las tiendas (como credit_note): cada tienda ve las cantidades que se
--     devolvieron o se están devolviendo en otra tienda, para no ofrecer de más una venta propia.
--   * sale_return_conflict solo existe en la central y no se replica: es el registro para revisión del panel de tiendas.

-- Sucursal que acepta devoluciones de ventas hechas en otras sucursales. La central la cambia; las tiendas la reciben
-- por la réplica de branch (su disparador ya registra los cambios).
ALTER TABLE branch ADD COLUMN accepts_foreign_returns BOOLEAN NOT NULL DEFAULT false;

-- Cantidades apartadas por una devolución. La clave es la clave de idempotencia de la devolución: al subir la devolución
-- a la central, sus reservas pasan a CONFIRMED y la devolución queda registrada en la venta original.
-- RESERVED: apartada, aún no confirmada. CONFIRMED: la devolución llegó a la central. RELEASED: la devolución falló.
CREATE TABLE sale_return_claim (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_key       VARCHAR(100)  NOT NULL,
    -- Sin claves foráneas: la venta y su línea pueden venir de otra tienda o llegar después por la réplica.
    sale_id         BIGINT        NOT NULL,
    sale_line_id    BIGINT        NOT NULL,
    quantity        NUMERIC(12,3) NOT NULL,
    store_node_id   BIGINT        NOT NULL,
    return_sale_id  BIGINT,
    status          VARCHAR(10)   NOT NULL,
    created_at      TIMESTAMPTZ   NOT NULL,
    created_by      VARCHAR(50)   NOT NULL,
    updated_at      TIMESTAMPTZ   NOT NULL,
    updated_by      VARCHAR(50)   NOT NULL,
    version         INT           NOT NULL DEFAULT 0,
    CONSTRAINT sale_return_claim_quantity_ck CHECK (quantity > 0),
    CONSTRAINT sale_return_claim_status_ck CHECK (status IN ('RESERVED', 'CONFIRMED', 'RELEASED')),
    CONSTRAINT sale_return_claim_key_line_uk UNIQUE (claim_key, sale_line_id)
);

CREATE INDEX sale_return_claim_sale_idx ON sale_return_claim (sale_id);

-- Réplica de las reservas a todas las tiendas: mismo disparador que las demás tablas principales (ver V9).
CREATE TRIGGER sync_log_sale_return_claim AFTER INSERT OR UPDATE OR DELETE ON sale_return_claim
    FOR EACH ROW EXECUTE FUNCTION sync_log_change('sale_return_claim', 'id', 'main');

-- Devoluciones que devolvieron más de lo que quedaba en una línea (una devolución sin conexión chocó con otra).
-- La central aceptó el documento, topó la cantidad devuelta en la línea y guarda aquí el excedente para revisión.
CREATE TABLE sale_return_conflict (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id         BIGINT        NOT NULL,
    sale_line_id    BIGINT        NOT NULL,
    return_sale_id  BIGINT        NOT NULL,
    store_node_id   BIGINT        NOT NULL,
    excess_quantity NUMERIC(12,3) NOT NULL,
    created_at      TIMESTAMPTZ   NOT NULL,
    created_by      VARCHAR(50)   NOT NULL,
    updated_at      TIMESTAMPTZ   NOT NULL,
    updated_by      VARCHAR(50)   NOT NULL,
    version         INT           NOT NULL DEFAULT 0,
    CONSTRAINT sale_return_conflict_excess_ck CHECK (excess_quantity > 0)
);

CREATE INDEX sale_return_conflict_store_idx ON sale_return_conflict (store_node_id);
