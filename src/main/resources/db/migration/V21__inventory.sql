-- V21: inventario, paso 1 (núcleo). Ver docs/plan.md, "MVP 4: inventario" y "Decisiones de implementación: inventario
-- paso 1 (núcleo)".
--   * inventory_item es la existencia por producto y sucursal. Guarda copias del producto (sku, nombre, categoría y
--     mínimo) que se refrescan con cada movimiento; así la búsqueda, el orden y la alerta de mínimo se resuelven en la
--     base de datos sin leer las tablas del catálogo.
--   * Los documentos, sus líneas, los movimientos y los contadores son documentos: no se replican por disparadores.
--     Las tiendas los suben a la central con sync_outbox.
--   * inventory_movement es inmutable: el saldo se puede reconstruir sumando las cantidades.

CREATE TABLE inventory_item (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id        BIGINT        NOT NULL REFERENCES product (id),
    branch_id         BIGINT        NOT NULL REFERENCES branch (id),
    -- Puede ser negativa solo en sucursales con allow_negative_stock.
    quantity          NUMERIC(12,3) NOT NULL DEFAULT 0,
    -- Costo promedio ponderado por sucursal.
    average_cost      NUMERIC(14,4) NOT NULL DEFAULT 0 CHECK (average_cost >= 0),
    -- Copias del producto, refrescadas en cada movimiento.
    product_sku       VARCHAR(40)   NOT NULL,
    product_name      VARCHAR(200)  NOT NULL,
    category_id       BIGINT        REFERENCES category (id),
    min_stock         NUMERIC(12,3) NOT NULL DEFAULT 0 CHECK (min_stock >= 0),
    last_movement_at  TIMESTAMPTZ,
    created_at        TIMESTAMPTZ   NOT NULL,
    created_by        VARCHAR(50)   NOT NULL,
    updated_at        TIMESTAMPTZ   NOT NULL,
    updated_by        VARCHAR(50)   NOT NULL,
    version           INT           NOT NULL DEFAULT 0,
    CONSTRAINT inventory_item_product_branch_uk UNIQUE (product_id, branch_id)
);

CREATE INDEX inventory_item_branch_id_idx ON inventory_item (branch_id);
CREATE INDEX inventory_item_product_name_idx ON inventory_item (lower(product_name));
CREATE INDEX inventory_item_product_sku_idx ON inventory_item (product_sku);

-- Contador de números de documento por sucursal y tipo (mismo patrón que cash_register_counter).
CREATE TABLE inventory_document_counter (
    branch_id    BIGINT      NOT NULL REFERENCES branch (id),
    type         VARCHAR(15) NOT NULL CHECK (type IN ('ENTRY', 'EXIT', 'ADJUSTMENT')),
    last_number  BIGINT      NOT NULL DEFAULT 0 CHECK (last_number >= 0),
    created_at   TIMESTAMPTZ NOT NULL,
    created_by   VARCHAR(50) NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL,
    updated_by   VARCHAR(50) NOT NULL,
    version      INT         NOT NULL DEFAULT 0,
    PRIMARY KEY (branch_id, type)
);

CREATE TABLE inventory_document (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id        BIGINT        NOT NULL REFERENCES branch (id),
    -- Formato {TIPO}-{código de sucursal}-{000001}. Único en todo el sistema.
    number           VARCHAR(30)   NOT NULL UNIQUE,
    type             VARCHAR(15)   NOT NULL CHECK (type IN ('ENTRY', 'EXIT', 'ADJUSTMENT')),
    -- Obligatorio en salidas y ajustes; opcional en entradas.
    reason           VARCHAR(200),
    notes            VARCHAR(500),
    idempotency_key  VARCHAR(64)   UNIQUE,
    posted_at        TIMESTAMPTZ   NOT NULL,
    user_id          BIGINT        NOT NULL REFERENCES app_user (id),
    -- Momento en que la central recibió el documento; NULL mientras está solo en la tienda.
    synced_at        TIMESTAMPTZ,
    created_at       TIMESTAMPTZ   NOT NULL,
    created_by       VARCHAR(50)   NOT NULL,
    updated_at       TIMESTAMPTZ   NOT NULL,
    updated_by       VARCHAR(50)   NOT NULL,
    version          INT           NOT NULL DEFAULT 0,
    CONSTRAINT inventory_document_reason_ck CHECK (
        type = 'ENTRY' OR (reason IS NOT NULL AND btrim(reason) <> ''))
);

CREATE INDEX inventory_document_branch_posted_idx ON inventory_document (branch_id, posted_at);

CREATE TABLE inventory_document_line (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id        BIGINT        NOT NULL REFERENCES inventory_document (id),
    product_id         BIGINT        NOT NULL REFERENCES product (id),
    -- Cambio de la existencia que aplicó la línea, con signo.
    quantity           NUMERIC(12,3) NOT NULL,
    -- Cantidad contada (solo en ajustes).
    counted_quantity   NUMERIC(12,3),
    previous_quantity  NUMERIC(12,3) NOT NULL,
    unit_cost          NUMERIC(14,4),
    created_at         TIMESTAMPTZ   NOT NULL,
    created_by         VARCHAR(50)   NOT NULL,
    updated_at         TIMESTAMPTZ   NOT NULL,
    updated_by         VARCHAR(50)   NOT NULL,
    version            INT           NOT NULL DEFAULT 0,
    CONSTRAINT inventory_document_line_product_uk UNIQUE (document_id, product_id)
);

-- Bitácora de movimientos de inventario. No se modifica ni se borra.
CREATE TABLE inventory_movement (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id              BIGINT        NOT NULL REFERENCES branch (id),
    product_id             BIGINT        NOT NULL REFERENCES product (id),
    type                   VARCHAR(20)   NOT NULL CHECK (type IN ('ENTRY', 'EXIT', 'ADJUSTMENT', 'SALE_OUT',
                                                                  'RETURN_IN', 'TRANSFER_OUT', 'TRANSFER_IN')),
    -- Cantidad con signo: positiva entra, negativa sale.
    quantity               NUMERIC(12,3) NOT NULL,
    resulting_balance      NUMERIC(12,3) NOT NULL,
    unit_cost              NUMERIC(14,4) NOT NULL,
    resulting_average_cost NUMERIC(14,4) NOT NULL,
    reference_type         VARCHAR(20)   NOT NULL CHECK (reference_type IN ('INVENTORY_DOCUMENT', 'SALE', 'SALE_RETURN',
                                                                            'TRANSFER')),
    reference_id           BIGINT        NOT NULL,
    moved_at               TIMESTAMPTZ   NOT NULL,
    user_id                BIGINT        NOT NULL REFERENCES app_user (id),
    created_at             TIMESTAMPTZ   NOT NULL,
    created_by             VARCHAR(50)   NOT NULL,
    updated_at             TIMESTAMPTZ   NOT NULL,
    updated_by             VARCHAR(50)   NOT NULL,
    version                INT           NOT NULL DEFAULT 0
);

CREATE INDEX inventory_movement_branch_product_moved_idx ON inventory_movement (branch_id, product_id, moved_at);
CREATE INDEX inventory_movement_reference_idx ON inventory_movement (reference_type, reference_id);
