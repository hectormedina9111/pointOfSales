-- V6: catálogo (categorías, unidades de medida, impuestos y productos).
--
-- Ver docs/plan.md, sección "Catálogo" y "Reglas de negocio del catálogo". Desviaciones
-- documentadas en "Decisiones de implementación: paso 4 (catálogo)":
--   * unit_of_measure lleva active (la regla UNIT_INACTIVE lo necesita).
--   * product_tax tiene id propio y UNIQUE (product_id, country_id), con columnas de auditoría.
--   * min_stock es NOT NULL con DEFAULT 0.

-- Búsqueda de productos por parte del nombre (ILIKE con índice trigram).
CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE category (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Jerarquía: NULL en las categorías raíz. Los ciclos los evita el dominio.
    parent_id   BIGINT       REFERENCES category (id),
    name        VARCHAR(100) NOT NULL,
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL,
    created_by  VARCHAR(50)  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL,
    updated_by  VARCHAR(50)  NOT NULL,
    version     INT          NOT NULL DEFAULT 0
);

CREATE INDEX category_parent_id_idx ON category (parent_id);

CREATE TABLE unit_of_measure (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(10)  NOT NULL UNIQUE,
    name            VARCHAR(50)  NOT NULL,
    -- FALSE para piezas (UNIT); TRUE para peso o volumen (KG, LB, LT).
    allows_decimals BOOLEAN      NOT NULL DEFAULT FALSE,
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ  NOT NULL,
    created_by      VARCHAR(50)  NOT NULL,
    updated_at      TIMESTAMPTZ  NOT NULL,
    updated_by      VARCHAR(50)  NOT NULL,
    version         INT          NOT NULL DEFAULT 0
);

CREATE TABLE tax (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id  BIGINT        NOT NULL REFERENCES country (id),
    code        VARCHAR(20)   NOT NULL,
    name        VARCHAR(80)   NOT NULL,
    rate        NUMERIC(5,2)  NOT NULL CHECK (rate >= 0 AND rate <= 100),
    active      BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ   NOT NULL,
    created_by  VARCHAR(50)   NOT NULL,
    updated_at  TIMESTAMPTZ   NOT NULL,
    updated_by  VARCHAR(50)   NOT NULL,
    version     INT           NOT NULL DEFAULT 0,
    -- El código es único por país; la clave compuesta también sirve de índice por país.
    CONSTRAINT tax_country_code_uk UNIQUE (country_id, code)
);

CREATE TABLE product (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku                         VARCHAR(40)   NOT NULL UNIQUE,
    -- Varios productos pueden no tener código de barras; UNIQUE ignora los NULL.
    barcode                     VARCHAR(50)   UNIQUE,
    name                        VARCHAR(200)  NOT NULL,
    description                 TEXT,
    category_id                 BIGINT        REFERENCES category (id),
    -- Impuesto del país principal; los demás países van en product_tax.
    tax_id                      BIGINT        NOT NULL REFERENCES tax (id),
    unit_of_measure_id          BIGINT        NOT NULL REFERENCES unit_of_measure (id),
    sale_price                  NUMERIC(14,2) NOT NULL CHECK (sale_price >= 0),
    -- Siempre TRUE: el precio incluye ISV y la base se calcula hacia atrás.
    price_includes_tax          BOOLEAN       NOT NULL DEFAULT TRUE CHECK (price_includes_tax),
    cost                        NUMERIC(14,2) CHECK (cost IS NULL OR cost >= 0),
    tracks_inventory            BOOLEAN       NOT NULL DEFAULT TRUE,
    tracks_serials              BOOLEAN       NOT NULL DEFAULT FALSE,
    requires_exclusive_invoice  BOOLEAN       NOT NULL DEFAULT FALSE,
    min_stock                   NUMERIC(12,3) NOT NULL DEFAULT 0 CHECK (min_stock >= 0),
    image_url                   VARCHAR(300),
    active                      BOOLEAN       NOT NULL DEFAULT TRUE,
    product_type                VARCHAR(10)   NOT NULL DEFAULT 'GOOD' CHECK (product_type IN ('GOOD', 'SERVICE')),
    created_at                  TIMESTAMPTZ   NOT NULL,
    created_by                  VARCHAR(50)   NOT NULL,
    updated_at                  TIMESTAMPTZ   NOT NULL,
    updated_by                  VARCHAR(50)   NOT NULL,
    version                     INT           NOT NULL DEFAULT 0,
    -- Un servicio nunca mueve inventario ni lleva seriales.
    CONSTRAINT product_service_rules_ck CHECK (
        product_type <> 'SERVICE' OR (tracks_inventory = FALSE AND tracks_serials = FALSE)),
    -- Los seriales exigen inventario.
    CONSTRAINT product_serials_inventory_ck CHECK (tracks_serials = FALSE OR tracks_inventory = TRUE)
);

CREATE INDEX product_category_id_idx ON product (category_id);
CREATE INDEX product_tax_id_idx ON product (tax_id);
CREATE INDEX product_unit_of_measure_id_idx ON product (unit_of_measure_id);
-- Búsqueda por parte del nombre sin distinguir mayúsculas.
CREATE INDEX product_name_trgm_idx ON product USING GIN (lower(name) gin_trgm_ops);

-- Impuesto de un producto para otro país. Si no hay fila para el país, se usa product.tax_id.
CREATE TABLE product_tax (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT       NOT NULL REFERENCES product (id),
    country_id  BIGINT       NOT NULL REFERENCES country (id),
    tax_id      BIGINT       NOT NULL REFERENCES tax (id),
    created_at  TIMESTAMPTZ  NOT NULL,
    created_by  VARCHAR(50)  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL,
    updated_by  VARCHAR(50)  NOT NULL,
    version     INT          NOT NULL DEFAULT 0,
    -- Un producto tiene como máximo un impuesto por país.
    CONSTRAINT product_tax_product_country_uk UNIQUE (product_id, country_id)
);

CREATE INDEX product_tax_tax_id_idx ON product_tax (tax_id);
