-- V12: cajas y métodos de pago (paso 1 del MVP 3A).
--
-- Ver docs/plan.md, "MVP 3A: caja y venta" y "Decisiones de implementación: 3A paso 1". Desviaciones:
--   * cash_register no tiene last_receipt_number. El correlativo de recibos es local de cada tienda y se guarda
--     en una tabla que solo existe en la tienda (paso 3). En la central, la réplica lo sobrescribiría.
--   * Las dos tablas son datos maestros de la central: sus cambios se registran con sync_log_change y llegan a
--     las tiendas por la réplica. Las tablas son nuevas, así que no hay filas previas que cargar.
--   * role_default_grant registra los privilegios por defecto que ya se aplicaron a un rol (RoleDefaultsSeeder).
--     Solo existe en la central y no se replica: así un privilegio que el administrador quita no vuelve.

CREATE TABLE cash_register (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id       BIGINT        NOT NULL REFERENCES branch (id),
    -- Punto de emisión dentro de la sucursal, ej.: 001.
    code            VARCHAR(10)   NOT NULL,
    name            VARCHAR(80)   NOT NULL,
    -- Prefijo de los recibos de esta caja, ej.: REC-001-001-.
    receipt_prefix  VARCHAR(20)   NOT NULL,
    active          BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ   NOT NULL,
    created_by      VARCHAR(50)   NOT NULL,
    updated_at      TIMESTAMPTZ   NOT NULL,
    updated_by      VARCHAR(50)   NOT NULL,
    version         INT           NOT NULL DEFAULT 0,
    -- El código es único dentro de cada sucursal. La clave compuesta también sirve de índice por sucursal.
    CONSTRAINT cash_register_branch_code_uk UNIQUE (branch_id, code),
    CONSTRAINT cash_register_code_ck CHECK (btrim(code) <> ''),
    CONSTRAINT cash_register_name_ck CHECK (btrim(name) <> ''),
    CONSTRAINT cash_register_receipt_prefix_ck CHECK (btrim(receipt_prefix) <> '')
);

CREATE TABLE payment_method (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Código fijo del sistema (CASH, CARD, TRANSFER). Lo crea el sembrado de la central; la API no lo crea ni lo cambia.
    code                VARCHAR(20)   NOT NULL UNIQUE,
    name                VARCHAR(60)   NOT NULL,
    -- Exige una referencia, como la autorización del POS bancario.
    requires_reference  BOOLEAN       NOT NULL DEFAULT FALSE,
    -- Solo el efectivo da vuelto: el monto cobrado puede ser mayor que la venta.
    allows_change       BOOLEAN       NOT NULL DEFAULT FALSE,
    active              BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ   NOT NULL,
    created_by          VARCHAR(50)   NOT NULL,
    updated_at          TIMESTAMPTZ   NOT NULL,
    updated_by          VARCHAR(50)   NOT NULL,
    version             INT           NOT NULL DEFAULT 0,
    CONSTRAINT payment_method_name_ck CHECK (btrim(name) <> '')
);

-- Réplica: mismos triggers que V9, para las dos tablas principales.
CREATE TRIGGER sync_log_cash_register AFTER INSERT OR UPDATE OR DELETE ON cash_register
    FOR EACH ROW EXECUTE FUNCTION sync_log_change('cash_register', 'id', 'main');
CREATE TRIGGER sync_log_payment_method AFTER INSERT OR UPDATE OR DELETE ON payment_method
    FOR EACH ROW EXECUTE FUNCTION sync_log_change('payment_method', 'id', 'main');

-- Registro de privilegios por defecto ya aplicados a un rol. Solo en la central; no tiene triggers de réplica.
CREATE TABLE role_default_grant (
    role_code       VARCHAR(30)   NOT NULL,
    privilege_code  VARCHAR(100)  NOT NULL,
    applied_at      TIMESTAMPTZ   NOT NULL,
    PRIMARY KEY (role_code, privilege_code)
);
